  // ── Flights ───────────────────────────────────────────────────────────────
  static List<FlightModel> flights({
    String? origin,
    String? destination,
    String? originCity,
    String? destinationCity,
    DateTime? departureDate,
  }) {
    final originAirport = AirportOption.byCode(origin ?? 'MJI');
    final destinationAirport = AirportOption.byCode(destination ?? 'CAI');
    final originCode = originAirport?.code ?? origin ?? 'MJI';
    final destinationCode = destinationAirport?.code ?? destination ?? 'CAI';
    if (originCode == destinationCode) return [];

    final fromCity = originCity ?? originAirport?.city ?? originCode;
    final toCity =
        destinationCity ?? destinationAirport?.city ?? destinationCode;
    final isLibyanRoute = originAirport?.country == 'Libya' ||
        destinationAirport?.country == 'Libya';
    final isDomesticLibyanRoute = originAirport?.country == 'Libya' &&
        destinationAirport?.country == 'Libya';
    final base = departureDate ?? DateTime.now().add(const Duration(days: 7));
    final carriers = isLibyanRoute
        ? const [
            ('Libyan Airlines', 'LN'),
            ('Afriqiyah Airways', '8U'),
            ('Buraq Air', 'UZ'),
          ]
        : const [
            ('EgyptAir', 'MS'),
            ('Turkish Airlines', 'TK'),
            ('Qatar Airways', 'QR'),
          ];
    final durations = isDomesticLibyanRoute
        ? const [55, 70, 85]
        : isLibyanRoute
            ? const [135, 190, 245]
            : const [195, 270, 330];
    final prices = isDomesticLibyanRoute
        ? const [95.0, 125.0, 145.0]
        : isLibyanRoute
            ? const [185.0, 245.0, 310.0]
            : const [280.0, 340.0, 420.0];
    const departureHours = [7, 13, 20];

    return List.generate(3, (index) {
      final departure = DateTime(
        base.year,
        base.month,
        base.day,
        departureHours[index],
        index == 1 ? 30 : 15,
      );
      final duration = durations[index];
      final carrier = carriers[index];
      return FlightModel(
        id: 'demo-$originCode-$destinationCode-$index',
        airline: carrier.$1,
        airlineCode: carrier.$2,
        flightNumber: '${carrier.$2} ${210 + index * 37}',
        originCode: originCode,
        originCity: fromCity,
        destinationCode: destinationCode,
        destinationCity: toCity,
        departureTime: departure,
        arrivalTime: departure.add(Duration(minutes: duration)),
        durationMinutes: duration,
        isDirect: index != 1,
        stops: index == 1 ? 1 : 0,
        economyPrice: prices[index],
        businessPrice: index == 0 ? prices[index] * 2.8 : null,
        seatsAvailable: 8 + index * 9,
      );
    });
  }

